-- DeepWork: whether the user has been asked about pinning the app somewhere
-- they can reach it in one click.
--
-- The ask is a card with two answers — pin it, or not now — and either answer is
-- recorded here, because "not now" is an answer: nothing in this app asks the
-- same question twice, and a taskbar prompt that came back on every launch would
-- be the nagging kind of reminder rather than the helpful kind.
--
-- On Windows the answer is not the only thing that matters: the shell is asked
-- whether DeepWork is *already* pinned, and being pinned there ends the question
-- whatever this column says. Everywhere else macOS and Linux keep their pinned
-- apps in stores no application may read, so this column is what keeps the offer
-- to a single appearance.
ALTER TABLE settings ADD COLUMN taskbar_pin_prompted INTEGER NOT NULL DEFAULT 0;
